const {chromium}=require('/Users/ayellowspace/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
  const browser=await chromium.launch({headless:true,channel:'chrome'});
  const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  const externalRequests=[];
  page.on('request',r=>{if(/^https?:/.test(r.url()))externalRequests.push(r.url());});
  page.on('response',r=>{if(r.status()>=400)errors.push(`${r.status()} ${r.url()}`)});
  fs.mkdirSync('tests/screenshots',{recursive:true});
  const click=selector=>page.locator(selector).click();
  const act=name=>click(`[data-action="${name}"]`);
  const doc=async id=>{if(!await page.locator(`[data-doc="${id}"]`).count())await click(`[data-doc-open="${id}"]`);};
  const clue=key=>click(`[data-clue="${key}"]`);
  const stamp=async(i,type)=>{await click(`[data-claim="${i}"]`);await click(`[data-stamp="${type}"]`);};
  const next=async()=>{await act('submit');assert(await page.locator('dialog[open]').count());await act('next-chapter');};
  const target=process.env.GAME_URL || 'http://127.0.0.1:4173';
  if(target.startsWith('file:'))await page.context().setOffline(true);
  await page.goto(target);
  await page.evaluate(()=>document.fonts.ready);
  assert(await page.evaluate(()=>document.fonts.check('12px "Atlas Pixel"','图鉴档案袋')),'Chinese pixel font loads');
  await page.screenshot({path:'tests/screenshots/landing.png',fullPage:true});
  await act('start');
  for(const selector of ['.portrait','.photo','.paper']){
    const loaded=await page.locator(selector).first().evaluate(async el=>{
      const url=getComputedStyle(el).backgroundImage;
      if(!url.startsWith('url('))return false;
      const image=new Image();image.src=url.slice(5,-2);
      try{await image.decode();return image.naturalWidth>0;}catch{return false;}
    });
    assert(loaded,`${selector} background image loads offline`);
  }
  await page.screenshot({path:'tests/screenshots/chapter-1.png',fullPage:true});
  await act('submit');
  assert.equal(await page.locator('dialog[open]').count(),0,'Incomplete evidence must not advance');
  await doc('samples');await clue('sample-a');await clue('draft-both');
  await doc('factory');await act('flip');await doc('draft1');await clue('photo-pending');await clue('draft-direct');
  await doc('inspection');await doc('receipt');
  await stamp(0,'include');await stamp(1,'include');await stamp(2,'include');await act('submit');
  assert.equal(await page.locator('dialog[open]').count(),0,'Unsupported final destination must be rejected');
  await stamp(2,'pending');await next();
  await clue('photo-date');await clue('repair-date');
  await doc('draft2');await clue('draft-every');await doc('family');await clue('photo-date');
  await stamp(0,'include');await stamp(1,'include');await stamp(2,'private');await act('submit');
  assert.equal(await page.locator('dialog[open]').count(),0,'Unredacted data must not be submitted');
  await doc('repair');await click('[data-redact="name"]');await click('[data-redact="address"]');
  await doc('letter');
  await page.reload();await act('start');
  assert.equal(await page.locator('.chapter-heading h1').innerText(),'照片里没有等待','Chapter survives reload');
  await doc('repair');assert.equal(await page.locator('.redact.hidden').count(),2,'Redaction survives reload');
  await page.screenshot({path:'tests/screenshots/chapter-2.png',fullPage:true});
  await next();
  await clue('original-message');await clue('received-message');
  await doc('action');await clue('action-clear');await doc('original');await clue('original-message');
  await doc('followup');
  await stamp(0,'include');await stamp(1,'include');await stamp(2,'pending');await next();
  assert(await page.locator('[data-action="publish"]').isDisabled(),'Publication requires a test read');
  await click('[data-entry="0:question"]');await click('[data-entry="1:question"]');await click('[data-entry="2:question"]');
  await act('test-read');assert((await page.locator('.speech').innerText()).includes('这只手'));
  await click('[data-cover="1"]');assert(await page.locator('[data-action="publish"]').isDisabled(),'Changing cover invalidates test read');
  await act('test-read');assert((await page.locator('.speech').innerText()).includes('等维修'));
  await click('[data-cover="2"]');await act('test-read');assert((await page.locator('.speech').innerText()).includes('保存下来'));
  await click('[data-cover="0"]');await act('test-read');
  await page.screenshot({path:'tests/screenshots/chapter-4.png',fullPage:true});
  await act('publish');await act('add-blank');assert((await page.locator('h1').innerText()).includes('仍然打开'));
  await page.screenshot({path:'tests/screenshots/ending.png',fullPage:true});
  await act('view-atlas');assert(await page.locator('dialog[open]').count());await act('close-modal');
  await page.reload();await act('start');assert(await page.locator('[data-action="view-atlas"]').count(),'Published ending survives reload');
  await act('restart');await act('confirm-restart');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'tests/screenshots/mobile.png',fullPage:true});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  assert.equal(overflow,false,'Mobile layout must not overflow horizontally');
  assert.equal(errors.length,0,errors.join('\n'));
  if(target.startsWith('file:'))assert.equal(externalRequests.length,0,'Offline HTML makes no network requests');
  console.log(JSON.stringify({result:'PASS',verified:['Four-act full playthrough','Missing evidence and incorrect stamps blocked','Privacy redaction required','Save and reload','All three reader branches','Retest after editing','Publish and ending','Replay','390px mobile layout','No browser errors'],screenshots:'tests/screenshots'},null,2));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
